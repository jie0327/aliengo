// 带调参入口的构造函数：保存机器人模型、最新传感器状态、步态计划及采样周期，再建立滤波系统。
// robotModel/lowState/contact/phase 都是指针，指向控制框架共享的数据；保存指针后可在每次 run() 读取新值。
// contact 为4维计划接触标志（1支撑、0摆动），不是足端力传感器的实测接触；phase 为各腿当前阶段的归一化进度。
// dt 的单位是秒；Qdig 是18维过程噪声对角项，顺序与状态一致；testName 用于统计对象命名。
// 函数名后的冒号开启 C++ 成员初始化列表，在进入花括号内的函数体之前初始化对应成员。
Estimator::Estimator(QuadrupedRobot *robotModel, LowlevelState* lowState, 
                     VecInt4 *contact, Vec4 *phase, double dt, Vec18 Qdig,
                     std::string testName)
          :_robModel(robotModel), _lowState(lowState), _contact(contact),
           _phase(phase), _dt(dt), _Qdig(Qdig), _estName(testName){

    _initSystem();
}

// 常用构造函数：接口不传噪声参数时，按基座位置、基座速度、四足位置三组设置默认过程噪声。
Estimator::Estimator(QuadrupedRobot *robotModel, LowlevelState* lowState, 
                     VecInt4 *contact, Vec4 *phase, double dt)
          :_robModel(robotModel), _lowState(lowState), _contact(contact), 
           _phase(phase), _dt(dt){

    // rows() 返回 Eigen 向量行数；下标从0开始，0~2为位置、3~5为速度、6~17为足端位置。
    // 这些数是滤波调参用的协方差项，而不是位置或速度本身；不同状态分量的物理单位不同。
    for(int i(0); i<_Qdig.rows(); ++i){
        if(i < 3){
            _Qdig(i) = 0.0003;
        }
        else if(i < 6){
            _Qdig(i) = 0.0003;
        }
        else{
            _Qdig(i) = 0.01;
        }
    }

    _estName = "current";

    _initSystem();

}

// 析构函数在对象销毁时调用；此处沿用原实现的空函数体。
Estimator::~Estimator(){
}

